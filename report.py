"""Generate README.md from the curated document-AI/OCR registry."""

from __future__ import annotations

from collections import defaultdict

from __version__ import __version__
from data import TOOLS, Category, Tool


def _badge(label: str, message: str, color: str) -> str:
    label = label.replace(" ", "%20")
    message = str(message).replace(" ", "%20").replace("-", "--")
    return f"![{label}](https://img.shields.io/badge/{label}-{message}-{color})"


def _row(t: Tool) -> str:
    link = t.repo or t.homepage
    name = f"[{t.name}]({link})" if link else t.name
    oss = "🔓" if t.open_source else "🔒"
    return f"| {name} | {t.org} | {oss} {t.license} | {t.note} |"


def generate() -> str:
    total = len(TOOLS)
    oss = sum(1 for t in TOOLS if t.open_source)
    categories = sorted({t.category for t in TOOLS}, key=lambda c: c.label)

    by_cat: dict[Category, list[Tool]] = defaultdict(list)
    for t in TOOLS:
        by_cat[t.category].append(t)

    out: list[str] = []
    out.append("<!-- AUTO-GENERATED by report.py — run `python main.py generate` to refresh. -->")
    out.append("# 📄 Document AI & OCR Directory\n")
    out.append(" ".join([
        _badge("version", __version__, "blue"),
        _badge("tools", total, "green"),
        _badge("open source", oss, "brightgreen"),
        _badge("categories", len(categories), "purple"),
        "[![CI](https://github.com/Amarel-Taylor-Scott/document-ai-ocr-directory/actions/workflows/ci.yml/badge.svg)]"
        "(https://github.com/Amarel-Taylor-Scott/document-ai-ocr-directory/actions/workflows/ci.yml)",
        "[![License: MIT](https://img.shields.io/badge/License-MIT-yellow.svg)](LICENSE)",
    ]))
    out.append("")
    out.append("> A curated, machine-readable directory of **Document AI & OCR** tools — OCR "
               "engines, document parsers (PDF → Markdown/JSON), layout/table extraction, and "
               "managed Document AI APIs.\n")
    out.append("This repo catalogs public projects/products with links and key attributes "
               "(open-source, license), and ships a small CLI to search/filter/export the "
               "registry. No third-party code is vendored here.\n")

    out.append("## Quick start\n")
    out.append("```bash")
    out.append("pip install -e .              # stdlib-only; no runtime deps")
    out.append("doc-dir list                  # list all")
    out.append("doc-dir list --open-source    # only OSS")
    out.append("doc-dir search tables         # search name/org/note/tags")
    out.append("doc-dir export --format csv > document-ai.csv")
    out.append("doc-dir generate              # regenerate this README")
    out.append("```\n")

    out.append("## At a glance\n")
    out.append(f"- **{total}** tools across **{len(categories)}** categories")
    out.append(f"- **{oss}** open-source (🔓) · **{total - oss}** managed/proprietary (🔒)\n")

    out.append("## Directory\n")
    for cat in sorted(by_cat, key=lambda c: c.label):
        tools = sorted(by_cat[cat], key=lambda t: t.name.lower())
        out.append(f"### {cat.label} ({len(tools)})\n")
        out.append("| Name | Org | License | Notes |")
        out.append("|------|-----|---------|-------|")
        out.extend(_row(t) for t in tools)
        out.append("")

    out.append("## Choosing one (rules of thumb)\n")
    out.append("- **Plain OCR (self-host):** Tesseract, PaddleOCR, EasyOCR, docTR.")
    out.append("- **PDF → clean markdown for RAG:** Docling, Marker, MinerU, Unstructured.")
    out.append("- **Tables:** Camelot / pdfplumber (text PDFs), Table Transformer (images).")
    out.append("- **Math / scientific:** Nougat (OSS) or Mathpix (API).")
    out.append("- **Don't want to run models:** Textract, Azure DI, Google Document AI, LlamaParse, Reducto.\n")
    out.append("> Note licenses: some strong open parsers are copyleft (MinerU AGPL-3.0, "
               "Marker GPL-3.0 with a commercial option) — check before commercial use.\n")

    out.append("## Contributing\n")
    out.append("Add or correct an entry in [`data.py`](data.py), run `python main.py generate`, "
               "and open a PR. See [CONTRIBUTING.md](CONTRIBUTING.md) and "
               "[CODE_OF_CONDUCT.md](CODE_OF_CONDUCT.md). Record the exact license; omit "
               "anything you can't verify.\n")

    out.append("## License\n")
    out.append("[MIT](LICENSE) © Amarel Taylor Scott. Catalog metadata only; each listed "
               "project is governed by its own license.\n")
    return "\n".join(out)


if __name__ == "__main__":
    print(generate())
